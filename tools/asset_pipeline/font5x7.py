ADVANCE = 6  # 5 px glyph + 1 px letter spacing


def export(path: Path) -> None:
    payload = {
        "name": "fd-5x7",
        "width": 5,
        "height": 7,
        "advance": ADVANCE,
        "baseline": 7,
        "glyphs": {ch: rows for ch, rows in G.items()},
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(payload, indent=1) + "\n"
    path.write_text(text, encoding="utf-8")
    # JS twin so the game bootstraps with plain <script> tags (works in film pages)
    js_path = path.with_suffix(".js")
    js_path.write_text(
        "// AUTO-GENERATED by tools/asset_pipeline/font5x7.py -- do not edit.\n"
        "window.FD_FONT = " + json.dumps(payload) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    export(root / "game/assets/fonts/font5x7.json")
    print(f"font glyphs: {len(G)}")
