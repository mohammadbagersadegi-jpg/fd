#!/usr/bin/env python3
"""Bundle the JSON configs into a JS file the game (and film pages) can load.

The browser build always reads config/*.json through fetch when served over
HTTP.  Film pages are served from a custom scheme, so they ship with a
generated data.js instead.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONFIG = ROOT / "config"
OUT = ROOT / "game/src/generated/data.js"

FILES = ["movement", "collision", "combat", "animation", "stage", "presentation"]

HEADER = """// AUTO-GENERATED by tools/asset_pipeline/bundle_data.py -- do not edit.
// Source of truth: config/*.json
(function () {
  const DATA = {
"""


def main():
    parts = []
    for name in FILES:
        data = json.loads((CONFIG / f"{name}.json").read_text(encoding="utf-8"))
        parts.append(f"    {name}: {json.dumps(data, indent=2, ensure_ascii=False)}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + ",\n".join(parts) + "\n  };\n  window.FD_DATA = DATA;\n})();\n", encoding="utf-8")
    print(f"bundled {len(FILES)} configs -> {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
